#!/usr/bin/env node
/**
 * Generate public/_headers — the Content Security Policy — from the basemaps
 * crashmap.config.json actually names.
 *
 * The policy is a STATIC header: it cannot change when the reader presses the
 * basemap toggle, and a tile origin missing from it fails with an empty map
 * and a console error no reader will ever see. Writing it by hand means the
 * policy and the config drift the first time someone changes a basemap, and
 * the symptom appears nowhere near the edit.
 *
 * So the origins are taken from basemaps.js, which is the same file the
 * config validator checks the chosen ids against. A basemap the config can
 * name is a basemap the policy permits, by construction, and choosing "none"
 * really does leave a page that makes no external request at all.
 *
 * scripts/serve-csp.mjs applies this file to the local server, so `npm start`
 * and `npm test` both run under the real policy. `astro preview` sends no
 * security headers, which is how a build that instantiated WebAssembly at
 * import -- refused by its own CSP -- reached production in this project's
 * ancestor with nothing local having ever said so.
 *
 *   node site/scripts/build-headers.mjs   ->  site/public/_headers
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cspOrigins, basemap } from '../src/lib/basemaps.js';
import { load as loadConfig } from '../../pipeline/config.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const cfg = loadConfig(join(root, '..', 'crashmap.config.json'));
const ids = cfg.basemaps;
const { connect, img, font } = cspOrigins(ids);

const join1 = (arr) => (arr.length ? ' ' + arr.join(' ') : '');

/* script-src is 'self' and nothing else, and that is the point: every
   dependency is bundled and self-hosted, so no CDN can execute here. A CDN
   entry is the realistic attack on a static site, which is why the list is
   empty rather than short. */
const csp = [
  "default-src 'self'",
  "script-src 'self'",
  /* Astro inlines small styles and the charts set a handful of properties
     inline; neither can execute. */
  "style-src 'self' 'unsafe-inline'",
  `img-src 'self' data: blob:${join1(img)}`,
  `font-src 'self'${join1(font)}`,
  `connect-src 'self'${join1(connect)}`,
  /* MapLibre parses vector tiles in a worker created from a blob URL. */
  "worker-src 'self' blob:",
  "child-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'self'",
].join('; ');

const described = ids.map((id) => {
  const b = basemap(id);
  const origins = [...new Set([...(b.csp.connect || []), ...(b.csp.img || []),
    ...(b.csp.font || [])])];
  return `#   ${id.padEnd(22)} ${b.kind.padEnd(7)} ${origins.join(' ') || '(no external origin)'}`;
}).join('\n');

writeFileSync(join(root, 'public/_headers'), `# GENERATED by scripts/build-headers.mjs — do not edit.
#
# In the Cloudflare Pages header format, because that is a format static hosts
# understand. These are not here for a deployment: scripts/serve-csp.mjs reads
# this file and applies it to the local server, so "npm start" and "npm test"
# both run under the real policy rather than under no policy at all.
#
# The tile origins below are exactly the ones this build's configured basemaps
# need, taken from src/lib/basemaps.js. Change "basemaps" in
# crashmap.config.json and rebuild, and this file follows.
#
# Basemaps configured:
${described}

/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: geolocation=(), camera=(), microphone=(), payment=(), usb=()
  Cross-Origin-Opener-Policy: same-origin

# The data bundle is rebuilt as a SET -- facts.parquet, meta.json, summary.json
# and the rest have to agree with each other -- and the filenames do not change
# between builds. Caching one of them hard while another is re-fetched is how a
# dashboard ends up charting one build's numbers against another's field list,
# so these revalidate rather than being pinned.
/data/*
  Cache-Control: public, max-age=300, must-revalidate

# Astro content-hashes everything under _astro/, so a stale one is never served
# for being cached: a changed file is a changed URL.
/_astro/*
  Cache-Control: public, max-age=31536000, immutable
`);

console.log(`--> wrote public/_headers for ${ids.join(', ')}`);
console.log(`    connect-src 'self'${join1(connect)}`);
